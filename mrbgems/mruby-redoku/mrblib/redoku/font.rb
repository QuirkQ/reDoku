    # Pixel width of `text` at `scale`, without the trailing inter-glyph gap.
    def self.width(text, scale)
      return 0 if text.empty?
      text.size * (WIDTH + GAP) * scale - GAP * scale
    end

    # Draws `text` with its top-left corner at (x, y). Unknown characters
    # advance the cursor but draw nothing.
    def self.draw(display, text, x, y, scale, gray)
      cursor = x
      text.each_char do |ch|
        rows = GLYPHS[ch]
        if rows
          rows.each_with_index do |row, ry|
            row.size.times do |rx|
              next unless row[rx] == '#'
              display.fill_rect(cursor + rx * scale, y + ry * scale,
                                scale, scale, gray)
            end
          end
        end
        cursor += (WIDTH + GAP) * scale
      end
      display
    end
  end
end
